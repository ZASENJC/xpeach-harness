import { createRequire } from 'node:module'
const require = createRequire('/Volumes/SN 770/Developer/deepseek-harness/apps/web/package.json')
const { chromium } = require('playwright')
const url = process.argv[2]
const key = process.argv[3]
const browser = await chromium.launch({ headless: true })
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } })
await page.goto(url, { waitUntil: 'domcontentloaded' })
await page.waitForTimeout(9000)
await page.getByText('Settings').first().click()
await page.waitForTimeout(3000)
const overlay = page.locator('[class*="overlay"]').last()
await overlay.getByText('XPeach').first().click()
await page.waitForTimeout(3000)
await overlay.locator('input[type="password"], input[placeholder*="sk-"], input').first().fill(key)
await overlay.getByText(/^Bind$/).click()
await page.waitForTimeout(4000)
await page.screenshot({ path: '/tmp/xpeach-shots/B5-rebound.png' })
const txt = await overlay.evaluate(e => e.innerText)
console.log('REBOUND:', txt.slice(0, 800))
await browser.close()
