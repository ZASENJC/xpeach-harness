import { createRequire } from 'node:module'
const require = createRequire('/Volumes/SN 770/Developer/deepseek-harness/apps/web/package.json')
const { chromium } = require('playwright')
const url = process.argv[2]
const browser = await chromium.launch({ headless: true })
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } })
await page.goto(url, { waitUntil: 'domcontentloaded' })
await page.waitForTimeout(9000)
await page.getByText('Settings').first().click()
await page.waitForTimeout(2500)
await page.getByText(/Model/).first().click()
await page.waitForTimeout(3000)
await page.getByText('Edit').first().click()
await page.waitForTimeout(2000)
await page.getByText('Customized settings').click()
await page.waitForTimeout(2000)
await page.screenshot({ path: '/tmp/xpeach-shots/A5-models-list.png' })
console.log('model-id inputs:', await page.locator('input[placeholder*="Model ID"]').count())
const ids = await page.locator('input[placeholder*="Model ID"]').evaluateAll(els => els.map(e => e.value))
console.log('ids:', ids)
await browser.close()
