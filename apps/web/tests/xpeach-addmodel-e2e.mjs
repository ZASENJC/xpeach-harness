import { createRequire } from 'node:module'
const require = createRequire('/Volumes/SN 770/Developer/deepseek-harness/apps/web/package.json')
const { chromium } = require('playwright')
const url = process.argv[2]
const browser = await chromium.launch({ headless: true })
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } })
await page.goto(url, { waitUntil: 'domcontentloaded' })
await page.waitForTimeout(9000)
await page.getByText('Settings').first().click()
await page.waitForTimeout(2500)
await page.getByText(/Model/).first().click()
await page.waitForTimeout(3000)
await page.getByText('Edit').first().click()
await page.waitForTimeout(2000)
await page.getByText('Customized settings').click()
await page.waitForTimeout(1500)
await page.getByText(/Add model/).first().click()
await page.waitForTimeout(1500)
const inputs = page.locator('input')
await inputs.nth(7).fill('peach-mutate-e2e')
await inputs.nth(8).fill('Peach Mutate E2E')
await page.waitForTimeout(1000)
await page.getByText('Apply').last().click()
await page.waitForTimeout(4000)
await page.screenshot({ path: '/tmp/xpeach-shots/A4-applied.png' })
console.log('apply done')
await browser.close()
