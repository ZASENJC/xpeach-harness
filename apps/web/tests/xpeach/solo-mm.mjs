import { chromium } from 'playwright'
const h = await import('./harness.mjs')
const b = await chromium.launch({ headless: true })
const p = await b.newPage({ viewport: { width: 1440, height: 900 } })
await p.goto(process.env.XPEACH_URL, { waitUntil: 'domcontentloaded' })
await p.waitForTimeout(10000)
await h.openConsole(p)
await p.waitForTimeout(2000)
await p.getByText(/Model Market|模型市场/).click()
await p.waitForTimeout(3000)
const row = p.locator('[class*="marketRow"]').filter({ hasText: 'claude-sonnet-4-6' }).first()
console.log('row buttons:', (await row.locator('button').allInnerTexts()).join(' | '))
await row.getByRole('button').last().click()
await p.waitForTimeout(2500)
await p.screenshot({ path: '/tmp/xpeach-shots/G9-join.png' })
await h.ensureComposer(p)
const chip = p.getByRole('button', { name: /swe-|claude-|gemini-|grok-/i }).filter({ hasNotText: /New Session|Console/ }).last()
console.log('chip:', await chip.innerText().catch(()=>'none'))
await chip.click(); await p.waitForTimeout(1800)
const hits = await p.getByText('claude-sonnet-4-6', { exact: true }).count()
console.log('sonnet in picker:', hits)
await p.screenshot({ path: '/tmp/xpeach-shots/G9-picker.png' })
await b.close()
